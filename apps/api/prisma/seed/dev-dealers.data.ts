/**
 * The seed rows, with the town flattened in and the three derived columns built.
 *
 * `slug` is **derived rather than written**, through the same `dealerSlug` the
 * registration path uses. A hundred and twenty hand-typed slugs were a hundred
 * and twenty chances for the seed to disagree with the function that produces
 * every real one — and the disagreement would be invisible, because a
 * hand-typed slug is a perfectly valid slug. Deriving it means correcting a
 * town in `TOWNS` corrects the addresses that follow from it, in the URL and in
 * the bucket, without anybody remembering to.
 *
 * `mapsUrl` is composed here rather than stored per dealer because these pins
 * are the town's, not the yard's — a real dealer pastes their own Share link at
 * onboarding, and inventing a hundred and twenty distinct `maps.app.goo.gl`
 * short codes would be inventing links that resolve to nothing.
 */
export const DEV_DEALERS: DevDealerRow[] = DEALERS.map((dealer, index) => {
  const town = TOWNS[dealer.town];
  return {
    ...dealer,
    ...town,
    slug: dealerSlug({
      legalName: dealer.legalName,
      city: town.city,
      district: town.district,
      state: town.state,
    }),
    mapsUrl: `https://www.google.com/maps/search/?api=1&query=${String(town.lat)},${String(town.lng)}`,
    workingHours: hoursFor(index),
  };
});
