export function findComponent(query: string): RegistryEntry[] {
  const needle = query.trim().toLowerCase();
  if (needle === '') return registry;

  return registry.filter((entry) =>
    [entry.name, entry.purpose, entry.category, ...entry.aliases]
      .join(' ')
      .toLowerCase()
      .includes(needle),
  );
}
