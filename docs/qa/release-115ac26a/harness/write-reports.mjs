// Renders the result-driven reports from registry/results.final.json (run finalize.mjs first),
// so every table in them is the recorded verdict, not a transcription.
import { readFileSync, writeFileSync } from "node:fs";
import { dirname, resolve } from "node:path";
import { fileURLToPath } from "node:url";

const ROOT = resolve(dirname(fileURLToPath(import.meta.url)), "..");
const results = JSON.parse(
  readFileSync(resolve(ROOT, "registry/results.final.json"), "utf8"),
);
const { scenarios } = JSON.parse(
  readFileSync(resolve(ROOT, "registry/registry.json"), "utf8"),
);
const counts = JSON.parse(
  readFileSync(resolve(ROOT, "EVIDENCE/final-counts.json"), "utf8"),
);
const SHA = counts.sha;
const byId = Object.fromEntries(scenarios.map((s) => [s.id, s]));
const sections = [...new Set(scenarios.map((s) => s.section))];
const discoveredIds = Object.keys(results).filter((id) => !byId[id]);

const cell = (v) =>
  String(v ?? "")
    .replace(/\|/g, "\\|")
    .replace(/\n/g, " ");
const short = (t, n = 220) =>
  t && t.length > n ? `${t.slice(0, n - 1)}…` : (t ?? "");
const mark = (s) =>
  ({
    PASS: "PASS",
    FAIL: "**FAIL**",
    BLOCKED: "_BLOCKED_",
    NOT_APPLICABLE: "N/A",
  })[s] ?? s;

function table(ids) {
  const rows = [
    "| ID | Scenario | Result | Layers | Evidence / note | Bug |",
    "| --- | --- | --- | --- | --- | --- |",
  ];
  for (const id of ids) {
    const rec = results[id];
    if (!rec) continue;
    const text = byId[id]?.text ?? "_discovered_";
    const note = rec.triage
      ? `${short(rec.note, 160)} **Triage:** ${short(rec.triage, 200)}`
      : short(rec.note);
    rows.push(
      `| ${id} | ${cell(text)} | ${mark(rec.status)} | ${cell((rec.layers ?? []).join(", "))} | ${cell(note)} | ${rec.bug ?? ""} |`,
    );
  }
  return rows.join("\n");
}
function tally(ids) {
  const t = { PASS: 0, FAIL: 0, BLOCKED: 0, NOT_APPLICABLE: 0 };
  for (const id of ids) if (results[id]) t[results[id].status] += 1;
  return t;
}
const tallyLine = (ids) => {
  const t = tally(ids);
  return `${ids.length} scenarios — PASS ${t.PASS} · FAIL ${t.FAIL} · BLOCKED ${t.BLOCKED} · NOT_APPLICABLE ${t.NOT_APPLICABLE}`;
};
const sectionIds = (...prefixes) =>
  scenarios.filter((s) => prefixes.includes(s.section)).map((s) => s.id);
const disc = (re) => discoveredIds.filter((id) => re.test(id));
const header = (title) =>
  `# ${title}\n\nAudited commit \`${SHA}\` · local isolated container · generated by \`harness/write-reports.mjs\` from \`registry/results.final.json\`. Evidence for each row is under \`EVIDENCE/<area>/\` (area = the harness script's recorder name; see \`TEST-TRACEABILITY.csv\`).\n\n`;

function doc(file, title, intro, groups) {
  const parts = [header(title), intro.trim(), ""];
  for (const [heading, ids] of groups) {
    if (!ids.length) continue;
    parts.push(`## ${heading}`, "", tallyLine(ids), "", table(ids), "");
  }
  writeFileSync(resolve(ROOT, file), `${parts.join("\n")}\n`);
}

// ── TEST-RESULTS.md ────────────────────────────────────────────────────────────
{
  const parts = [
    header("Test results — every canonical scenario"),
    `Canonical: **${counts.canonical.accounted} / 556 accounted**, missing ${counts.canonical.missing}, unclassified ${counts.canonical.unclassified} — PASS ${counts.canonical.PASS} · FAIL ${counts.canonical.FAIL} · BLOCKED ${counts.canonical.BLOCKED} · NOT_APPLICABLE ${counts.canonical.NOT_APPLICABLE}. Discovered: ${counts.discovered.total} — PASS ${counts.discovered.PASS} · FAIL ${counts.discovered.FAIL} · BLOCKED ${counts.discovered.BLOCKED} · NOT_APPLICABLE ${counts.discovered.NOT_APPLICABLE}.`,
    "",
    "A **Triage** note marks a verdict reviewed after the harness ran (`registry/triage.json`); where it changed the status, the harness verdict is kept as `harnessStatus` in `results.final.json`.",
    "",
  ];
  for (const sec of sections) {
    const ids = sectionIds(sec);
    parts.push(
      `## ${byId[ids[0]].sectionTitle} — ${sec}`,
      "",
      tallyLine(ids),
      "",
      table(ids),
      "",
    );
  }
  parts.push(
    "## Discovered scenarios",
    "",
    tallyLine(discoveredIds),
    "",
    table(discoveredIds),
    "",
  );
  writeFileSync(resolve(ROOT, "TEST-RESULTS.md"), `${parts.join("\n")}\n`);
}

