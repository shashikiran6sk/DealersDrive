#!/usr/bin/env node
// Canonical registry tool for the pre-production certification.
//
//   node docs/testing/pre-production/registry/registry.mjs validate
//       Parse canonical-scenarios.txt, assign IDs, assert 556 / 0 duplicates /
//       0 missing, and regenerate CANONICAL-TEST-REGISTRY.md + registry.json.
//
//   node docs/testing/pre-production/registry/registry.mjs completeness
//       Read results.json and print the Part X coverage-completeness table.
//       Exits non-zero unless every canonical ID carries exactly one of
//       PASS | FAIL | BLOCKED | NOT_APPLICABLE.
import { execFileSync } from 'node:child_process';
import { readFileSync, writeFileSync, existsSync } from 'node:fs';
import { dirname, resolve } from 'node:path';
import { fileURLToPath } from 'node:url';
import process from 'node:process';

const EXPECTED = 556;
const STATUSES = ['PASS', 'FAIL', 'BLOCKED', 'NOT_APPLICABLE'];

const here = dirname(fileURLToPath(import.meta.url));
const SOURCE = resolve(here, 'canonical-scenarios.txt');
const REGISTRY_JSON = resolve(here, 'registry.json');
const RESULTS_JSON = resolve(here, 'results.json');
const REGISTRY_MD = resolve(here, '..', 'CANONICAL-TEST-REGISTRY.md');

function parse() {
  const sections = [];
  const scenarios = [];
  const problems = [];
  let section = null;

  readFileSync(SOURCE, 'utf8')
    .split('\n')
    .forEach((raw, index) => {
      const line = raw.trim();
      if (!line || line.startsWith('#')) return;

      const header = line.match(/^@SECTION (\S+) (\d+) (.+)$/);
      if (header) {
        section = { prefix: header[1], declared: Number(header[2]), title: header[3], items: 0 };
        sections.push(section);
        return;
      }

      const item = line.match(/^(\d+)\. (.+)$/);
      if (!item || !section) {
        problems.push(`line ${index + 1}: unparseable: ${line}`);
        return;
      }

      section.items += 1;
      scenarios.push({
        number: Number(item[1]),
        id: `${section.prefix}-${String(section.items).padStart(3, '0')}`,
        section: section.prefix,
        sectionTitle: section.title,
        text: item[2],
      });
    });

  return { sections, scenarios, problems };
}

function validate() {
  const { sections, scenarios, problems } = parse();

  const ids = scenarios.map((s) => s.id);
  const duplicateIds = ids.filter((id, i) => ids.indexOf(id) !== i);
  const numbers = new Set(scenarios.map((s) => s.number));
  const missingNumbers = [];
  for (let n = 1; n <= EXPECTED; n += 1) if (!numbers.has(n)) missingNumbers.push(n);
  const outOfOrder = scenarios.filter((s, i) => s.number !== i + 1).map((s) => s.number);
  const texts = scenarios.map((s) => s.text.toLowerCase());
  const duplicateTexts = scenarios.filter((s, i) => texts.indexOf(s.text.toLowerCase()) !== i);
  const headerMismatches = sections.filter((s) => s.declared !== s.items);
  const declaredTotal = sections.reduce((sum, s) => sum + s.declared, 0);

  console.log('Canonical registry validation');
  console.log(`  Expected canonical count = ${EXPECTED}`);
  console.log(`  Parsed canonical count   = ${scenarios.length}`);
  console.log(`  Duplicate IDs            = ${duplicateIds.length}`);
  console.log(`  Missing IDs              = ${missingNumbers.length}`);
  console.log(`  Out-of-order numbers     = ${outOfOrder.length}`);
  console.log(`  Duplicate scenario text  = ${duplicateTexts.length}`);
  console.log(`  Unparseable lines        = ${problems.length}`);
  console.log(`  Sections                 = ${sections.length}`);
  console.log(`  Sum of declared headers  = ${declaredTotal}`);
  for (const s of headerMismatches) {
    console.log(
      `  NOTE header mismatch: ${s.prefix} declared ${s.declared}, contains ${s.items} — IDs run to ${s.prefix}-${String(s.items).padStart(3, '0')}`,
    );
  }
  problems.forEach((p) => console.log(`  ${p}`));

  const ok =
    scenarios.length === EXPECTED &&
    duplicateIds.length === 0 &&
    missingNumbers.length === 0 &&
    outOfOrder.length === 0 &&
    problems.length === 0;

  if (!ok) {
    console.log('RESULT: REGISTRY INVALID — fix the registry, not the application.');
    process.exit(1);
  }

  writeFileSync(REGISTRY_JSON, `${JSON.stringify({ expected: EXPECTED, scenarios }, null, 2)}\n`);
  writeFileSync(REGISTRY_MD, renderMarkdown(sections, scenarios, headerMismatches));
  execFileSync('pnpm', ['exec', 'prettier', '--write', REGISTRY_JSON, REGISTRY_MD], {
    stdio: 'ignore',
  });
  console.log('RESULT: REGISTRY VALID');
}

function renderMarkdown(sections, scenarios, headerMismatches) {
  const out = [
    '# Canonical Test Registry',
    '',
    'Generated by `registry/registry.mjs validate` from `registry/canonical-scenarios.txt`. Do not',
    'edit by hand — edit the source and regenerate.',
    '',
    `- Expected: **${EXPECTED}** · Parsed: **${scenarios.length}** · Duplicate IDs: **0** · Missing: **0**`,
    `- Sections: **${sections.length}**`,
    '',
  ];
  if (headerMismatches.length > 0) {
    out.push('## Registry corrections', '');
    out.push(
      "The brief's section headers sum to fewer than the 556 numbered scenarios. No scenario was",
      'dropped; the affected ID ranges were extended so every numbered scenario keeps an ID:',
      '',
    );
    for (const s of headerMismatches) {
      out.push(
        `- **${s.prefix}**: header declared ${s.declared}, the brief lists ${s.items} → IDs \`${s.prefix}-001\`…\`${s.prefix}-${String(s.items).padStart(3, '0')}\``,
      );
    }
    out.push('');
  }
  out.push('## Sections', '', '| Prefix | Section | Count | Range |', '| --- | --- | --- | --- |');
  for (const s of sections) {
    const own = scenarios.filter((x) => x.section === s.prefix);
    out.push(
      `| ${s.prefix} | ${s.title} | ${s.items} | #${own[0].number}–#${own[own.length - 1].number} |`,
    );
  }
  out.push('');
  for (const s of sections) {
    out.push(`## ${s.title} — ${s.prefix}`, '', '| # | ID | Scenario |', '| --- | --- | --- |');
    for (const x of scenarios.filter((y) => y.section === s.prefix)) {
      out.push(`| ${x.number} | ${x.id} | ${x.text.replace(/\|/g, '\\|')} |`);
    }
    out.push('');
  }
  return out.join('\n');
}

function completeness() {
  const { scenarios } = JSON.parse(readFileSync(REGISTRY_JSON, 'utf8'));
  const results = existsSync(RESULTS_JSON) ? JSON.parse(readFileSync(RESULTS_JSON, 'utf8')) : {};
  const tally = Object.fromEntries(STATUSES.map((s) => [s, 0]));
  let missing = 0;
  let unclassified = 0;

  for (const s of scenarios) {
    const status = results[s.id]?.status;
    if (status === undefined) missing += 1;
    else if (STATUSES.includes(status)) tally[status] += 1;
    else unclassified += 1;
  }
  const unknownIds = Object.keys(results).filter((id) => !scenarios.some((s) => s.id === id));
  const accounted = STATUSES.reduce((sum, s) => sum + tally[s], 0);

  console.log(`Canonical expected: ${EXPECTED}`);
  for (const s of STATUSES) console.log(`${s}: ${tally[s]}`);
  console.log(`TOTAL ACCOUNTED: ${accounted}`);
  console.log(`MISSING: ${missing}`);
  console.log(`UNCLASSIFIED: ${unclassified}`);
  console.log(`UNKNOWN IDS IN RESULTS: ${unknownIds.length}`);
  const complete = accounted === EXPECTED && missing === 0 && unclassified === 0;
  console.log(complete ? 'COMPLETENESS: OK' : 'CERTIFICATION INCOMPLETE');
  if (!complete) process.exit(1);
}

const command = process.argv[2] ?? 'validate';
if (command === 'validate') validate();
else if (command === 'completeness') completeness();
else {
  console.error(`unknown command: ${command}`);
  process.exit(2);
}
