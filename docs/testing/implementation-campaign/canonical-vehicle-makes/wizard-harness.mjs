import { chromium } from 'playwright-core';
import { readFileSync } from 'node:fs';
import { execSync } from 'node:child_process';
const [out, S, id] = process.argv.slice(2);
const sql = (q) => execSync(`PGPASSWORD=dealersdrive psql -h localhost -U dealersdrive -d dealersdrive -At -c "${q}"`).toString().trim();
const b = await chromium.launch();
const res = {};
for (const width of [390, 1280]) {
  sql(`update vehicles set make=null where id='${id}'`);
  const ctx = await b.newContext({ viewport: { width, height: 900 } });
  await ctx.addCookies([{ name: 'dd_session', value: readFileSync(`${S}/tok-owner`, 'utf8').trim(), domain: 'localhost', path: '/' }]);
  const p = await ctx.newPage();
  const errors = [];
  p.on('pageerror', (e) => errors.push(String(e)));
  await p.goto(`http://localhost:3000/dealer/vehicles/${id}/edit?step=basics`, { waitUntil: 'networkidle' });
  const box = p.getByRole('combobox', { name: /Make/ });
  const r = { combobox: await box.count() };
  await box.click();
  await box.pressSequentially('merc');
  r.optionsForMerc = await p.getByRole('listbox', { name: 'Makes' }).getByRole('option').allInnerTexts();
  await p.screenshot({ path: `${out}/make-search-${width}.png` });
  await box.fill('');
  await box.pressSequentially('tata motors');
  await p.keyboard.press('Tab');
  r.boxAfterAlias = await box.inputValue();
  await p.getByRole('button', { name: 'Save draft' }).click();
  await p.waitForLoadState('networkidle');
  await p.waitForTimeout(1500);
  r.storedAfterSave = sql(`select make from vehicles where id='${id}'`);
  sql(`update vehicles set make='Hindustan Ambassador Co' where id='${id}'`);
  await p.goto(`http://localhost:3000/dealer/vehicles/${id}/edit?step=basics`, { waitUntil: 'networkidle' });
  r.legacyBox = await box.inputValue();
  await box.click();
  r.firstOption = (await p.getByRole('listbox', { name: 'Makes' }).getByRole('option').first().innerText()).trim();
  await p.screenshot({ path: `${out}/make-legacy-${width}.png` });
  await p.keyboard.press('Escape');
  await p.getByRole('button', { name: 'Save draft' }).click();
  await p.waitForLoadState('networkidle');
  await p.waitForTimeout(1500);
  r.legacyAfterResave = sql(`select make from vehicles where id='${id}'`);
  r.overflow = await p.evaluate(() => document.documentElement.scrollWidth > innerWidth);
  r.pageErrors = errors;
  res[width] = r;
  await ctx.close();
}
console.log(JSON.stringify(res, null, 1));
await b.close();
