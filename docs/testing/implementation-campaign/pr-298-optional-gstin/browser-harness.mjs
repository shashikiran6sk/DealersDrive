import { chromium } from 'playwright-core';
import { readFileSync } from 'node:fs';
const [out, S, id] = process.argv.slice(2);
const b = await chromium.launch();
const ctx = await b.newContext({ viewport: { width: 390, height: 900 } });
await ctx.addCookies([{ name: 'dd_admin_session', value: readFileSync(`${S}/tok-super-admin`, 'utf8').trim(), domain: 'localhost', path: '/' }]);
const a = await ctx.newPage();
const res = {};
await a.goto(`http://localhost:3000/admin/dealers/${id}`, { waitUntil: 'networkidle' });
const review = a.getByLabel(/GST registration applicability review/);
const approve = a.getByRole('button', { name: 'Approve dealer' });
res.reviewFieldPresent = await review.count();
await a.locator('#approvalConfirm').fill('approve motor point');
res.disabledWithoutReview = await approve.isDisabled();
await review.fill('Short note');
res.disabledWithShortReview = await approve.isDisabled();
await review.scrollIntoViewIfNeeded();
await a.screenshot({ path: `${out}/admin-approve-no-gstin-390.png` });
await review.fill('Local test: turnover below threshold, case ref LOCAL-298-01');
res.enabledWithReview = await approve.isEnabled();
res.overflow = await a.evaluate(() => document.documentElement.scrollWidth > innerWidth);
await approve.click();
await a.waitForTimeout(3000);
await a.reload({ waitUntil: 'networkidle' });
res.statusAfter = (await a.locator('body').innerText()).match(/\bActive\b|Pending approval/)?.[0] ?? null;
await a.screenshot({ path: `${out}/admin-after-approve-390.png` });
console.log(JSON.stringify(res, null, 1));
await b.close();
